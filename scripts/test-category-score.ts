import assert from 'node:assert/strict';
import { categoryScores } from '../src/services/funds/categoryScore';
const near = (a: number, b: number, tolerance = 1e-10) => assert.ok(Math.abs(a - b) < tolerance, `${a} != ${b}`);
assert.equal(categoryScores([]), null);
assert.equal(categoryScores([1]), null);
assert.equal(categoryScores([NaN, 1]), null);
assert.equal(categoryScores([Infinity, 1]), null);
assert.deepEqual(categoryScores([1, 1, 1]), [50, 50, 50]);
const close = categoryScores([1, 1.001, 1.002, 1.003, 1.004])!;
assert.ok(close.every(n => n > 49 && n < 51), 'Tiny differences do not force 25-point gaps');
const ascending = categoryScores([0, .4, .5, 1.6, 2])!;
assert.ok(ascending.every((n, i) => n >= 0 && n <= 100 && (i === 0 || n > ascending[i - 1])));
assert.notEqual(ascending[1], 25, 'Grades are not percentile ranks');
near(ascending[2], 50);
const changed = categoryScores([0, .4, .500001, 1.6, 2])!;
assert.ok(changed.every((n, i) => Math.abs(n - ascending[i]) < .001), 'Small input changes give small output changes');
const reversed = categoryScores([2, 1.6, .5, .4, 0])!;
reversed.forEach((n, i) => near(n, ascending[ascending.length - i - 1]));
const two = categoryScores([1, 1.01])!;
assert.ok(two[0] > 49 && two[1] < 51, 'Two near-identical funds cannot receive 0 and 100');
const symmetric = categoryScores([-2, -1, 0, 1, 2])!;
near(symmetric[0] + symmetric[4], 100);near(symmetric[1] + symmetric[3], 100);
assert.ok(categoryScores([-Number.MAX_VALUE, 0, Number.MAX_VALUE])!.every(Number.isFinite));
console.log('PASS category grades: continuity, ordering, ties, small samples, non-finite inputs, negative metrics, outliers and bounds.');
