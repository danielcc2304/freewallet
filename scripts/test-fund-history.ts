import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {readFinancialTimesHistory,readFinancialTimesIdentity} from '../supabase/functions/_shared/financialTimesHistory';
import {firstUsableFundHistory,fundHistoryWindow} from '../src/services/funds/fundHistory';
import type {HistoricalDataPoint} from '../src/types/types';
const isin='LU0329355670',name='Robeco QI Emerging Markets Active Equities D €';
const html=`<h1>${name}</h1><div data-mod-config='{"symbol":"${isin}:EUR","xid":"535675774","assetClass":"Fund"}'></div>`;
const identity=readFinancialTimesIdentity(html,isin);
const payload=JSON.parse(readFileSync('scripts/fixtures/fund-history/robeco-ft.json','utf8'));
const quoteOnly=JSON.parse(readFileSync('scripts/fixtures/fund-history/robeco-yahoo-quote-only.json','utf8'));
assert.equal(quoteOnly.chart.result[0].timestamp,undefined,'Real Robeco Yahoo response is only a quote, not a time series');
const rows=readFinancialTimesHistory(payload,identity);
assert.equal(rows.length,29);assert.equal(rows.at(-1)?.price,399.92);assert.equal(rows.at(-1)?.at,'2026-10-15T00:00:00.000Z');
assert.equal(rows[0].at,'2026-09-03T00:00:00.000Z');
assert.throws(()=>readFinancialTimesIdentity(html,'LU0034353002'));
assert.throws(()=>readFinancialTimesIdentity(html+`<div data-mod-config='{"symbol":"${isin}:EUR","xid":"999","assetClass":"Fund"}'></div>`,isin));
assert.throws(()=>readFinancialTimesIdentity(html,isin,'USD'));
const usd=readFinancialTimesIdentity(html.replace(':EUR',':USD'),isin);
assert.equal(usd.currency,'USD');
assert.throws(()=>readFinancialTimesHistory(payload,usd));
for(const patch of [{CompanyName:name.replace('D €','I €')},{IssueType:'ETF'},{Currency:'USD'},{Symbol:'999'},{Status:0}])assert.throws(()=>readFinancialTimesHistory({...payload,Elements:[{...payload.Elements[0],...patch}]},identity));
assert.throws(()=>readFinancialTimesHistory({...payload,Dates:payload.Dates.map(()=>payload.Dates[0])},identity));
const end=Date.UTC(2026,9,17,12);
assert.equal(new Date(fundHistoryWindow('1M',{},Date.UTC(2026,2,31)).start).toISOString().slice(0,10),'2026-02-28');
assert.equal(new Date(fundHistoryWindow('1M',{},Date.UTC(2024,2,31)).start).toISOString().slice(0,10),'2024-02-29');
assert.equal(new Date(fundHistoryWindow('YTD',{},end).start).toISOString().slice(0,10),'2026-01-01');
assert.equal(new Date(fundHistoryWindow('ALL',{},end).start).toISOString().slice(0,10),'1900-01-01');
assert.equal(fundHistoryWindow('7D',{},end).days,15);
assert.equal(fundHistoryWindow('3M',{startDate:Date.UTC(2025,0,1),endDate:end},end).start,Date.UTC(2025,0,1));
assert.throws(()=>fundHistoryWindow('1M',{startDate:end+86400000,endDate:end},end));
const points:HistoricalDataPoint[]=rows.map(r=>({date:r.at.slice(0,10),timestamp:Date.parse(r.at),close:r.price,open:r.price,high:r.price,low:r.price,volume:0,currency:'EUR',source:'Financial Times'}));
assert.equal(await firstUsableFundHistory([async()=>[],async()=>points]),points);
assert.equal(await firstUsableFundHistory([async()=>{throw Error('Provider unavailable');},async()=>points]),points);
assert.equal(await firstUsableFundHistory([async()=>points.slice(0,1),async()=>points]),points,'A quote-only response cannot win the race');
let cancelled=false;
assert.equal(await firstUsableFundHistory([async signal=>new Promise(resolve=>signal.addEventListener('abort',()=>{cancelled=true;resolve([]);})),async()=>points]),points);
assert.equal(cancelled,true,'Slow losing provider is cancelled');
assert.deepEqual(await firstUsableFundHistory([async()=>[],async()=>{throw Error('Down');}]),[]);
const controller=new AbortController();controller.abort();
await assert.rejects(firstUsableFundHistory([async()=>points],controller.signal),{name:'AbortError'});
const inFlight=new AbortController();
const pending=firstUsableFundHistory([async()=>new Promise(()=>{})],inFlight.signal);inFlight.abort();
await assert.rejects(pending,{name:'AbortError'});
console.log('PASS: real Robeco quote-only regression + verified FT NAV series; exact class/ISIN/currency, dates, ranges, partial/error/slow providers and cancellation.');
