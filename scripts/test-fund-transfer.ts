import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { prepareFundTransfer } from '../src/services/fundTransfer';
import { normalizePortfolioTransactions } from '../src/services/portfolioPerformance';
import { reconcileTradePosition } from '../src/services/portfolioTradeReplay';
import { calculatePortfolioResults } from '../src/services/portfolioResults';
import type { Asset, PortfolioTransaction } from '../src/types/types';

const source: Asset = { id: 'source', symbol: 'LU0034353002', isin: 'LU0034353002', name: 'Source fund', type: 'fund', quantity: 100, purchasePrice: 50, currentPrice: 60, purchaseDate: '2026-01-01', currency: 'EUR' };
const destination: Asset = { id: 'destination', symbol: 'IE00BYX5NX33', isin: 'IE00BYX5NX33', name: 'New destination fund', type: 'fund', quantity: 0, purchasePrice: 0, currentPrice: 25, purchaseDate: source.purchaseDate, currency: 'EUR' };
const other: Asset = { ...source, id: 'other', symbol: 'OTHER', isin: undefined, type: 'stock' };
const day = '2026-10-16';
const near = (a: number, b: number) => assert.ok(Math.abs(a - b) < 1e-8, `${a} != ${b}`);
const prepared = prepareFundTransfer([source, other], source.id, destination.id, 1200, false, { sourcePrice: 61, destinationPrice: 25 }, day, destination);
const operation: PortfolioTransaction = { ...prepared.transaction, id: 'transfer-one', createdAt: day + 'T12:00:00Z', provenance: 'trade' };
const opening = normalizePortfolioTransactions([source], []);
const ledger = [operation, ...opening];
const proposed = reconcileTradePosition([source, other], prepared.assets, ledger, operation);
assert.equal(proposed[0].quantity, 80);
near(proposed[2].quantity, 48.8);
near(proposed[2].purchasePrice, 1000 / 48.8);
assert.equal(proposed[2].purchaseDate, source.purchaseDate);
assert.equal(proposed[1], other);
assert.equal(operation.total, 1220);
assert.equal(operation.transferBasis, 1000);
assert.equal(operation.estimated, false);
assert.equal(normalizePortfolioTransactions(proposed.filter(a => a.type === 'fund'), ledger).length, 2, 'A transfer-in must never manufacture another opening purchase');
const results = calculatePortfolioResults(proposed.filter(a => a.type === 'fund'), ledger);
assert.equal(results.resultUnavailableReason, undefined);
near(results.realizedGain, 0);
assert.throws(() => prepareFundTransfer([source], source.id, destination.id, 1200, false, {}, day, { ...destination, isin: source.isin, symbol: source.symbol }), /ISIN|distinto/);
assert.throws(() => prepareFundTransfer([source, { ...destination, id: 'already-held' }], source.id, destination.id, 1200, false, {}, day, destination), /cartera/);
assert.throws(() => prepareFundTransfer([source], source.id, destination.id, 7000, false, {}, day, destination), /importe/i);
assert.throws(() => prepareFundTransfer([source], source.id, destination.id, 1200, false, {}, day, { ...destination, quantity: 3 }), /sin participaciones/);
assert.throws(() => prepareFundTransfer([source], source.id, destination.id, 1200, false, {}, day, { ...destination, currentPrice: NaN }), /valoración/);
const complete = prepareFundTransfer([source], source.id, destination.id, 0, true, {}, day, destination);
assert.equal(complete.assets.length, 1);
assert.equal(complete.assets[0].quantity, 240);
assert.equal(complete.transaction.estimated, true);

const db = new PGlite();
const owner = '11111111-1111-4111-8111-111111111111';
const session = '22222222-2222-4222-8222-222222222222';
const migration = (name: string) => readFileSync('supabase/migrations/' + readdirSync('supabase/migrations').find(n => n.endsWith('_' + name + '.sql')), 'utf8');
const data = (assets: Asset[], transactions: PortfolioTransaction[]) => ({ freewallet_portfolio_v1: JSON.stringify({ version: 1, assets, transactions }) });
const commit = async (revision: number, mode: string, payload: unknown, id = crypto.randomUUID()) => {
    const response = await db.query<{ result: { revision: number; data: Record<string, string> } }>('select public.commit_portfolio($1,$2,$3,$4) result', [revision, id, mode, payload]);
    const record = response.rows[0].result;
    return { revision: record.revision, state: JSON.parse(record.data.freewallet_portfolio_v1) as { assets: Asset[]; transactions: PortfolioTransaction[] } };
};
try {
    await db.exec(`create role anon;create role authenticated;create schema auth;
        create table auth.users(id uuid primary key,email_confirmed_at timestamptz default now(),is_anonymous boolean default false);
        create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id) on delete cascade);
        create table auth.mfa_factors(id uuid primary key,user_id uuid,status text);
        create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
        create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
        grant usage on schema auth,public to anon,authenticated;
        insert into auth.users(id) values('${owner}');insert into auth.sessions values('${session}','${owner}');`);
    for (const name of ['portfolio_foundation', 'portfolio_commands', 'portfolio_mfa_guard', 'portfolio_command_validation', 'portfolio_opening_basis', 'portfolio_delta_commands', 'portfolio_chronological_trades', 'portfolio_fund_transfer_execution_prices', 'portfolio_new_fund_transfer_destination']) { try { await db.exec(migration(name)); } catch (error) { const e = error as { internalQuery?: string; internalPosition?: string }; console.error('Migration failed:', name, e.internalQuery?.slice(Number(e.internalPosition) - 150, Number(e.internalPosition) + 150)); throw error; } }
    assert.equal((await db.query<{ v: boolean }>("select has_function_privilege('anon','portfolio_private.write_state(bigint,uuid,text,jsonb)','EXECUTE') v")).rows[0].v, false);
    await db.exec(`set role authenticated;select set_config('request.jwt.claim.sub','${owner}',false);select set_config('request.jwt.claims','{"session_id":"${session}"}',false)`);
    let saved = await commit(-1, 'import', data([source, other], []));
    const initialRevision = saved.revision;
    const requestId = crypto.randomUUID();
    const payload = data(proposed, ledger);
    saved = await commit(saved.revision, 'save', payload, requestId);
    assert.equal(saved.state.assets.length, 3);
    near(saved.state.assets.find(a => a.id === destination.id)!.purchasePrice, 1000 / 48.8);
    assert.equal(saved.state.assets.find(a => a.id === source.id)!.quantity, 80);
    assert.equal(saved.state.transactions.length, 2);
    assert.equal((await commit(initialRevision, 'save', payload, requestId)).revision, saved.revision, 'Network retries cannot duplicate destination/transfer');
    const revision = saved.revision;
    const failing = prepareFundTransfer(saved.state.assets.map(a => ({ ...a, currentPrice: a.id === source.id ? 60 : 25 })), source.id, 'new-two', 600, false, { sourcePrice: 60, destinationPrice: 25 }, day, { ...destination, id: 'new-two', isin: 'FR0010148981', symbol: 'FR0010148981' });
    const second: PortfolioTransaction = { ...failing.transaction, id: 'second', createdAt: day + 'T13:00:00Z' };
    const rejected = async (assets: Asset[], transaction: PortfolioTransaction) => {
        await assert.rejects(commit(revision, 'save', data(assets, [transaction, ...saved.state.transactions])));
        const read = await db.query<{ r: { revision: number; data: Record<string, string> } }>('select public.read_portfolio() r');
        assert.equal(read.rows[0].r.revision, revision);
        const current = JSON.parse(read.rows[0].r.data.freewallet_portfolio_v1);
        assert.equal(current.assets.some((a: Asset) => a.id === 'new-two'), false, 'A failed command cannot leave an orphan fund');
        assert.equal(current.transactions.length, 2);
    };
    await rejected(failing.assets.map(a => a.id === 'new-two' ? { ...a, isin: source.isin, symbol: source.symbol } : a), { ...second, transferToAssetSymbol: source.symbol });
    await rejected(failing.assets.map(a => a.id === 'new-two' ? { ...a, type: 'stock' } : a), second);
    await rejected(failing.assets.map(a => a.id === other.id ? { ...a, quantity: 99 } : a), second);
    await rejected(failing.assets, { ...second, transferBasis: 999999 });
    // Existing destinations imported without a ledger get one opening basis each.
    const existingSource = { ...source, id: 'import-source' };
    const existingTarget = { ...destination, id: 'import-target', quantity: 10, purchasePrice: 20 };
    await db.exec('reset role');
    await db.query('delete from auth.users where id=$1', [owner]);
    await db.query('insert into auth.users(id) values($1)', [owner]);
    await db.query('insert into auth.sessions values($1,$2)', [session, owner]);
    await db.exec('set role authenticated');
    saved = await commit(-1, 'import', data([existingSource, existingTarget], []));
    const existing = prepareFundTransfer([existingSource, existingTarget], existingSource.id, existingTarget.id, 600, false, {}, day);
    const existingOperation: PortfolioTransaction = { ...existing.transaction, id: 'existing-transfer', createdAt: day + 'T14:00:00Z' };
    saved = await commit(saved.revision, 'save', data(existing.assets, [existingOperation, ...normalizePortfolioTransactions([existingSource, existingTarget], [])]));
    assert.equal(saved.state.assets.find(a => a.id === existingTarget.id)!.quantity, 34);
    near(saved.state.assets.find(a => a.id === existingTarget.id)!.purchasePrice, 700 / 34);
    // Full transfer into a fresh fund, and a retry through incremental RPC.
    const fresh = { ...destination, id: 'fresh', isin: 'FR0010148981', symbol: 'FR0010148981' };
    const current = saved.state.assets.map(a => ({ ...a, currentPrice: a.id === existingSource.id ? 60 : 25 }));
    const full = prepareFundTransfer(current, existingSource.id, fresh.id, 0, true, {}, day, fresh);
    const fullOp: PortfolioTransaction = { ...full.transaction, id: 'full-transfer', createdAt: day + 'T15:00:00Z' };
    const fullPayload = data(full.assets, [fullOp, ...saved.state.transactions]);
    const result = await db.query<{ result: { data: Record<string, string> } }>("select public.patch_portfolio($1,gen_random_uuid(),$2,'{}') result", [saved.revision, fullPayload]);
    const final = JSON.parse(result.rows[0].result.data.freewallet_portfolio_v1);
    assert.equal(final.assets.some((a: Asset) => a.id === existingSource.id), false);
    assert.equal(final.assets.some((a: Asset) => a.id === fresh.id), true);
    console.log('PASS: new/existing destination, partial/full transfer, conserved tax basis, no synthetic contribution, one atomic command, retries, invalid identity/type/amount, unrelated asset protection and rollback.');
} finally { await db.close(); }
